package io.github.ravindren_sm.openstream.provider

import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Authenticated encryption (AES-256-GCM) for small secrets such as the portal settings.
 *
 * The key comes from outside: in the app it is an Android Keystore key (hardware-backed where
 * the device allows, never exported); in unit tests it is an ordinary [SecretKey]. This class
 * does not store keys and never logs plaintext.
 *
 * Sealed layout: 1 version byte, 1 IV-length byte, the IV, then ciphertext plus the 16-byte
 * GCM tag. The IV is generated by the cipher on every [seal] (Keystore keys require this), so
 * sealing the same plaintext twice gives different output. Associated data, if given, is
 * authenticated but not stored: opening with different associated data fails.
 */
class AesGcmBox(private val key: SecretKey) {

    fun seal(plaintext: ByteArray, associatedData: ByteArray = EMPTY): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)               // cipher generates a fresh random IV
        if (associatedData.isNotEmpty()) cipher.updateAAD(associatedData)
        val iv = cipher.iv
        require(iv.size in 1..255) { "unexpected IV length" }
        val body = cipher.doFinal(plaintext)
        return ByteArray(2 + iv.size + body.size).also {
            it[0] = VERSION
            it[1] = iv.size.toByte()
            System.arraycopy(iv, 0, it, 2, iv.size)
            System.arraycopy(body, 0, it, 2 + iv.size, body.size)
        }
    }

    /** Throws [SealedBoxException] (no plaintext, no key detail) if the data is damaged or the key differs. */
    fun open(sealed: ByteArray, associatedData: ByteArray = EMPTY): ByteArray {
        if (sealed.size < 2 + MIN_IV + TAG_BYTES || sealed[0] != VERSION) throw SealedBoxException("unrecognized format")
        val ivLen = sealed[1].toInt() and 0xFF
        if (ivLen < MIN_IV || sealed.size < 2 + ivLen + TAG_BYTES) throw SealedBoxException("unrecognized format")
        return try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BYTES * 8, sealed, 2, ivLen))
            if (associatedData.isNotEmpty()) cipher.updateAAD(associatedData)
            cipher.doFinal(sealed, 2 + ivLen, sealed.size - 2 - ivLen)
        } catch (e: java.security.GeneralSecurityException) {
            throw SealedBoxException("authentication failed")
        }
    }

    companion object {
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val VERSION: Byte = 1
        private const val MIN_IV = 12
        private const val TAG_BYTES = 16
        private val EMPTY = ByteArray(0)
    }
}

/** Opening failed. The message never contains key or plaintext material. */
class SealedBoxException(message: String) : Exception(message)
